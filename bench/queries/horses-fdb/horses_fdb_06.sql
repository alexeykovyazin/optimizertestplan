SELECT
  COUNT(*)
FROM
  HORSE H
  LEFT JOIN LATERAL (
    SELECT
      R.BYDATE
    FROM
      REGISTRATION R
    WHERE R.CODE_HORSE = H.CODE_HORSE
      AND R.CODE_REGTYPE = 6
    ORDER BY R.BYDATE
    FETCH FIRST ROW ONLY
  ) IMPORT_INFO ON TRUE
  LEFT JOIN COVER ON COVER.CODE_HORSE = H.CODE_HORSE
