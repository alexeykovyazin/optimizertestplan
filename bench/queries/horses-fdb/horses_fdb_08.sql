SELECT
  COUNT(*)
FROM
  HORSE H
  LEFT JOIN (
    SELECT
      R.CODE_HORSE,
      MIN(R.BYDATE) AS BYDATE
    FROM
      REGISTRATION R
    WHERE R.CODE_REGTYPE = 6
    GROUP BY R.CODE_HORSE
  ) IMPORT_INFO ON IMPORT_INFO.CODE_HORSE = H.CODE_HORSE
  LEFT JOIN COVER ON COVER.CODE_HORSE = H.CODE_HORSE
