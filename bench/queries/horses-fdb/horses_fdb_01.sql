SELECT
  COUNT(*)
FROM
  HORSE H
  LEFT JOIN LATERAL (
    SELECT
      REGS.BYDATE,
      REGS.PREV_CODE_COUNTRY AS CODE_IMPORT_COUNTRY
    FROM
    (
      SELECT
        R.BYDATE,
        R.CODE_FARM,
        FARM.CODE_COUNTRY,
        LAG(FARM.CODE_COUNTRY) OVER(ORDER BY R.BYDATE) AS PREV_CODE_COUNTRY
      FROM
        REGISTRATION R
        JOIN FARM ON FARM.CODE_FARM = R.CODE_FARM
      WHERE R.CODE_HORSE = H.CODE_HORSE
        AND R.CODE_REGTYPE = 6
        AND FARM.CODE_COUNTRY > 0
    ) REGS
    WHERE REGS.CODE_COUNTRY IS DISTINCT FROM REGS.PREV_CODE_COUNTRY
      AND REGS.CODE_COUNTRY = 1
    ORDER BY REGS.BYDATE
    FETCH FIRST ROW ONLY
  ) IMPORT_INFO ON TRUE
  LEFT JOIN COVER ON COVER.CODE_HORSE = H.CODE_HORSE
