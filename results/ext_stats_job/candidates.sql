-- Кандидаты многоколоночных статистик для JOB + JOB-light (анализ 27.10.2026).
-- См. results/ext_stats_job/REPORT.md. Порядок: приоритет 1..3.
-- Каждая CREATE — в отдельной транзакции; сбор: один ALTER DATABASE REFRESH STATISTICS.
-- Шесть словарей CEB (KIND_TYPE, ROLE_TYPE, INFO_TYPE, LINK_TYPE, COMPANY_TYPE,
-- COMP_CAST_TYPE) уже созданы скриптом 26.10 — повторно не создаются.

-- Приоритет 1: TITLE
CREATE EXTENDED STATISTICS STAT_TITLE_ID_PROD_YEAR ON TITLE(ID, PRODUCTION_YEAR);
CREATE EXTENDED STATISTICS STAT_TITLE_KIND_ID_PROD_YEAR ON TITLE(KIND_ID, PRODUCTION_YEAR);
CREATE EXTENDED STATISTICS STAT_TITLE_ID_KIND_ID ON TITLE(ID, KIND_ID);

-- Приоритет 2: словари вне CEB-шестёрки
CREATE EXTENDED STATISTICS STAT_KEYWORD_ID_KEYWORD ON KEYWORD(ID, KEYWORD);
CREATE EXTENDED STATISTICS STAT_COMPANY_NAME_ID_COUNTRY ON COMPANY_NAME(ID, COUNTRY_CODE);
CREATE EXTENDED STATISTICS STAT_NAME_ID_GENDER ON NAME(ID, GENDER);
CREATE EXTENDED STATISTICS STAT_NAME_ID_NAME_PCODE_CF ON NAME(ID, NAME_PCODE_CF); -- опционально
CREATE EXTENDED STATISTICS STAT_CHAR_NAME_ID_NAME ON CHAR_NAME(ID, NAME);         -- опционально

-- Приоритет 3: факт-таблицы (join MOVIE_ID + равенство по типовой колонке)
CREATE EXTENDED STATISTICS STAT_MOVIE_INFO_MOVIE_ID_ITYPE ON MOVIE_INFO(MOVIE_ID, INFO_TYPE_ID);
CREATE EXTENDED STATISTICS STAT_MOVIE_INFO_IDX_MOV_ID_IT ON MOVIE_INFO_IDX(MOVIE_ID, INFO_TYPE_ID);
CREATE EXTENDED STATISTICS STAT_MOVIE_COMPANIES_MC_ID_CT ON MOVIE_COMPANIES(MOVIE_ID, COMPANY_TYPE_ID);
CREATE EXTENDED STATISTICS STAT_CAST_INFO_MOVIE_ID_ROLE ON CAST_INFO(MOVIE_ID, ROLE_ID);
CREATE EXTENDED STATISTICS STAT_MOVIE_KEYWORD_MOVIE_ID_KW ON MOVIE_KEYWORD(MOVIE_ID, KEYWORD_ID);

-- После CREATE: ALTER DATABASE REFRESH STATISTICS;
