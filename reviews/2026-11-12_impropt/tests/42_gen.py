#
# Every case is one outer join query in two forms:
#   H - the join keys are written as "x = y" / "x is not distinct from y":
#       the optimizer is free to take Hash Join (outer);
#   N - the same keys are written as ranges, "(x >= y and x <= y)" and
#       "((x >= y and x <= y) or (x is null and y is null))": no equi-join
#       conjunct exists, so the plan is always a nested loop. This is the reference.
# The generated script prints for every case:
#   "<tag> H"  - the H form alone (its EXPLAIN shows the chosen join method);
#   "<tag>"    - PASS/FAIL: the H and the N forms compared in one statement
#                by count(*), count(inner id) and a checksum of the joined ids.
#
# Placeholders in the case text:
#   {{EQ|x|y}}  join key, strong equality
#   {{ND|x|y}}  join key, IS NOT DISTINCT FROM
#   {{V|name}}  view name; the N form uses <name>_n (the view with range keys)
#
# Usage: python 42_gen.py   (writes the two files next to this script)

