def expand(text, form):
    def repl(m):
        kind = m.group(1)
        args = re.split(r"(?<!\|)\|(?!\|)", m.group(2))   # a single "|" separates, "||" is SQL
        if kind == "V":
            return args[0] if form == "H" else args[0] + "_n"
        x, y = args
        if form == "H":
            return "%s = %s" % (x, y) if kind == "EQ" else "%s is not distinct from %s" % (x, y)
        rng = "(%s >= %s and %s <= %s)" % (x, y, x, y)
        return rng if kind == "EQ" else "(%s or (%s is null and %s is null))" % (rng, x, y)

    prev = None
    while prev != text:
        prev = text
        text = PH.sub(repl, text)
    return text


