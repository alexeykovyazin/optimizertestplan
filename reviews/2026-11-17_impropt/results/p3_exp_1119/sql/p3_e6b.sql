SET LIST ON;
SET STATS ON;

SELECT 'X3' AS TBL,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MI * C_MII * C_MK) AS J1,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MC * C_MI * C_MII) AS J2,
  SUM(CAST(C_MI AS DOUBLE PRECISION) * C_MII * C_MK) AS J3,
  SUM(CAST(C_MI AS DOUBLE PRECISION) * C_MK) AS J4,
  SUM(CAST(C_MC AS DOUBLE PRECISION) * C_MI * C_MII * C_MK) AS J5,
  SUM(CAST(C_MC AS DOUBLE PRECISION) * C_MI * C_MK) AS J6,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MC * C_MK) AS J7,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MI * C_MK) AS J8,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MC * C_MI * C_MK) AS J9,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MI * C_MII) AS J10,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MC * C_MII * C_MK) AS J11,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MC * C_MI) AS J12,
  SUM(CAST(C_MC AS DOUBLE PRECISION) * C_MI) AS J13,
  SUM(CAST(C_MC AS DOUBLE PRECISION) * C_MI * C_MII) AS J14,
  SUM(CAST(C_MK AS DOUBLE PRECISION)) AS J15,
  SUM(CAST(C_MC AS DOUBLE PRECISION)) AS J16,
  SUM(CAST(C_MII AS DOUBLE PRECISION)) AS J17,
  SUM(CAST(C_CI AS DOUBLE PRECISION)) AS J18,
  SUM(CAST(C_CI AS DOUBLE PRECISION) * C_MK) AS J19
FROM X3_KEY;
