INSERT INTO X3_KEY (MOVIE_ID, C_CI, C_MK, C_MI, C_MC, C_MII, U)
SELECT d.movie_id, SUM(d.ci), SUM(d.mk), SUM(d.mi), SUM(d.mc), SUM(d.mii),
       BIN_AND(HASH(CAST(d.movie_id AS VARCHAR(12)) USING CRC32), 16777215) / 16777216e0
FROM (
  SELECT movie_id, COUNT(*) ci, 0 mk, 0 mi, 0 mc, 0 mii FROM cast_info GROUP BY movie_id
  UNION ALL
  SELECT movie_id, 0, COUNT(*), 0, 0, 0 FROM movie_keyword GROUP BY movie_id
  UNION ALL
  SELECT movie_id, 0, 0, COUNT(*), 0, 0 FROM movie_info GROUP BY movie_id
  UNION ALL
  SELECT movie_id, 0, 0, 0, COUNT(*), 0 FROM movie_companies GROUP BY movie_id
  UNION ALL
  SELECT movie_id, 0, 0, 0, 0, COUNT(*) FROM movie_info_idx GROUP BY movie_id
) d
GROUP BY d.movie_id;
COMMIT;
