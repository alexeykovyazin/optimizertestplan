CREATE TABLE X3_KEY (
  MOVIE_ID INTEGER NOT NULL,
  C_CI  BIGINT NOT NULL,
  C_MK  BIGINT NOT NULL,
  C_MI  BIGINT NOT NULL,
  C_MC  BIGINT NOT NULL,
  C_MII BIGINT NOT NULL,
  U DOUBLE PRECISION NOT NULL,
  CONSTRAINT X3_KEY_PK PRIMARY KEY (MOVIE_ID)
);
