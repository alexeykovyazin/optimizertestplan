SET LIST ON;
SET STATS ON;

WITH par AS (
  SELECT a.A, m.M
  FROM (SELECT 0e0 AS A FROM RDB$DATABASE UNION ALL
        SELECT 1e0 FROM RDB$DATABASE UNION ALL
        SELECT 1.5e0 FROM RDB$DATABASE) a
  CROSS JOIN
       (SELECT 256e0 AS M FROM RDB$DATABASE UNION ALL
        SELECT 1024e0 FROM RDB$DATABASE UNION ALL
        SELECT 4096e0 FROM RDB$DATABASE) m
),
tot AS (
  SELECT p.A, p.M,
    SUM(IIF(x.C_CI > 0, POWER(x.C_CI, p.A), 0e0)) / p.M AS T_CI,
    SUM(IIF(x.C_MK > 0, POWER(x.C_MK, p.A), 0e0)) / p.M AS T_MK
  FROM X3_KEY x CROSS JOIN par p
  GROUP BY p.A, p.M
),
k AS (
  SELECT t.A, t.M,
    CAST(x.C_CI AS DOUBLE PRECISION) * x.C_MK AS X,
    MINVALUE(1e0, POWER(x.C_CI, t.A) / t.T_CI, POWER(x.C_MK, t.A) / t.T_MK) AS PI
  FROM X3_KEY x CROSS JOIN tot t
  WHERE x.C_CI > 0 AND x.C_MK > 0
)
SELECT 'CI+MK' AS E2_SET, A, M,
  COUNT(*) AS KEYS,
  SUM(X) AS J,
  SUM(PI) AS MATCHED_EXPECTED,
  SQRT(SUM(X * X * (1e0 / PI - 1e0))) / SUM(X) AS CV
FROM k
GROUP BY A, M
ORDER BY A, M;

